export const buildHsk3ModalityTimeNarrationPack = (
  root = process.cwd(),
) => {
  const referenceBundle =
    loadHsk3ReferenceQuantityNarrationPackBundle(root);
  assertValidHsk3ReferenceQuantityNarrationPackBundle(referenceBundle);
  return buildHsk3NarrationGrammarModulePack({
    root,
    packId: HSK3_MODALITY_TIME_PACK_CONFIG.packId,
    trackId: HSK3_MODALITY_TIME_TRACK_ID,
    lessonIds: HSK3_MODALITY_TIME_LESSON_IDS,
    grammarDrafts: GRAMMAR_DRAFTS,
    narratives: NARRATIVES,
    prerequisitePackBundles: [referenceBundle],
    completedNarrationGrammarModules:
      HSK3_MODALITY_TIME_PACK_CONFIG.completedNarrationGrammarModules,
    completedNarrationGrammarLessons:
      HSK3_MODALITY_TIME_PACK_CONFIG.completedNarrationGrammarLessons,
  });
};

export const serializeHsk3ModalityTimeNarrationPack = (pack) =>
  `${JSON.stringify(pack)}\n`;

const main = () => {
  const outputPath = resolve(
    process.cwd(),
    HSK3_MODALITY_TIME_NARRATION_PACK_RELATIVE_PATH,
  );
  const serialized = serializeHsk3ModalityTimeNarrationPack(
    buildHsk3ModalityTimeNarrationPack(),
  );
  if (process.argv.includes("--write")) {
    writeFileSync(outputPath, serialized, "utf8");
  } else if (process.argv.includes("--check")) {
    if (readFileSync(outputPath, "utf8") !== serialized) {
      throw new Error("Checked HSK3 modality/time narration pack is stale");
    }
  } else {
    process.stdout.write(serialized);
  }
  console.log(JSON.stringify({
    valid: true,
    output: HSK3_MODALITY_TIME_NARRATION_PACK_RELATIVE_PATH,
    mode: process.argv.includes("--write")
      ? "write"
      : process.argv.includes("--check")
        ? "check"
        : "stdout",
  }, null, 2));
};

if (
  process.argv[1]
  && fileURLToPath(import.meta.url) === resolve(process.argv[1])
) {
  main();
}
