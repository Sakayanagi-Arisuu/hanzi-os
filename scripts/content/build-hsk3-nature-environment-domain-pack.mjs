export const buildHsk3NatureEnvironmentDomainPack = (
  root = process.cwd(),
) => {
  const studyWorkBundle = loadHsk3StudyWorkDomainPackBundle(root);
  assertValidHsk3StudyWorkDomainPackBundle(studyWorkBundle);
  return buildHsk3ParagraphDomainPack({
    root,
    packId: HSK3_NATURE_ENVIRONMENT_PACK_CONFIG.packId,
    domainId: HSK3_NATURE_ENVIRONMENT_DOMAIN_ID,
    lessonIds: HSK3_NATURE_ENVIRONMENT_LESSON_IDS,
    vietnameseGlossBySequence: VI_GLOSS_BY_SEQUENCE,
    content: CONTENT,
    prerequisitePackBundles: [studyWorkBundle],
    completedParagraphDomainCount:
      HSK3_NATURE_ENVIRONMENT_PACK_CONFIG.completedParagraphDomainCount,
    completedParagraphLessons:
      HSK3_NATURE_ENVIRONMENT_PACK_CONFIG.completedParagraphLessons,
  });
};

export const serializeHsk3NatureEnvironmentDomainPack = (pack) =>
  `${JSON.stringify(pack)}\n`;

const main = () => {
  const outputPath = resolve(
    process.cwd(),
    HSK3_NATURE_ENVIRONMENT_DOMAIN_PACK_RELATIVE_PATH,
  );
  const serialized = serializeHsk3NatureEnvironmentDomainPack(
    buildHsk3NatureEnvironmentDomainPack(),
  );
  if (process.argv.includes("--write")) {
    writeFileSync(outputPath, serialized, "utf8");
  } else if (process.argv.includes("--check")) {
    if (readFileSync(outputPath, "utf8") !== serialized) {
      throw new Error("Checked HSK3 nature/environment domain pack is stale");
    }
  } else {
    process.stdout.write(serialized);
  }
  console.log(JSON.stringify({
    valid: true,
    output: HSK3_NATURE_ENVIRONMENT_DOMAIN_PACK_RELATIVE_PATH,
    mode: process.argv.includes("--write")
      ? "write"
      : process.argv.includes("--check")
        ? "check"
        : "stdout",
  }, null, 2));
};

if (
  process.argv[1]
  && fileURLToPath(import.meta.url) === resolve(process.argv[1])
) {
  main();
}
