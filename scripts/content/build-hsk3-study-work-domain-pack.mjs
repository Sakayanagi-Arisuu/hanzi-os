export const buildHsk3StudyWorkDomainPack = (root = process.cwd()) => {
  const personalBundle = loadHsk3PersonalDomainPackBundle(root);
  assertValidHsk3PersonalDomainPackBundle(personalBundle);
  return buildHsk3ParagraphDomainPack({
    root,
    packId: HSK3_STUDY_WORK_PACK_CONFIG.packId,
    domainId: HSK3_STUDY_WORK_DOMAIN_ID,
    lessonIds: HSK3_STUDY_WORK_LESSON_IDS,
    vietnameseGlossBySequence: VI_GLOSS_BY_SEQUENCE,
    content: CONTENT,
    prerequisitePackBundles: [personalBundle],
    completedParagraphDomainCount:
      HSK3_STUDY_WORK_PACK_CONFIG.completedParagraphDomainCount,
    completedParagraphLessons:
      HSK3_STUDY_WORK_PACK_CONFIG.completedParagraphLessons,
  });
};

export const serializeHsk3StudyWorkDomainPack = (pack) =>
  `${JSON.stringify(pack)}\n`;

const main = () => {
  const outputPath = resolve(
    process.cwd(),
    HSK3_STUDY_WORK_DOMAIN_PACK_RELATIVE_PATH,
  );
  const serialized = serializeHsk3StudyWorkDomainPack(
    buildHsk3StudyWorkDomainPack(),
  );
  if (process.argv.includes("--write")) {
    writeFileSync(outputPath, serialized, "utf8");
  } else if (process.argv.includes("--check")) {
    if (readFileSync(outputPath, "utf8") !== serialized) {
      throw new Error("Checked HSK3 study/work domain pack is stale");
    }
  } else {
    process.stdout.write(serialized);
  }
  console.log(JSON.stringify({
    valid: true,
    output: HSK3_STUDY_WORK_DOMAIN_PACK_RELATIVE_PATH,
    mode: process.argv.includes("--write")
      ? "write"
      : process.argv.includes("--check")
        ? "check"
        : "stdout",
  }, null, 2));
};

if (
  process.argv[1]
  && fileURLToPath(import.meta.url) === resolve(process.argv[1])
) {
  main();
}
